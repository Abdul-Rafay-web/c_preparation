import { useState } from 'react';
import { SlidersHorizontal, ShieldCheck } from 'lucide-react';
import type { DashboardData } from '../types';

interface Props {
  data: DashboardData;
}

const PYTORCH_SNIPPET = `# PyTorch QAT + 75% Pruned Model (Python)
class JetMLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            QFixedLinear(16, 64, bits=6, int_bits=2),
            QFixedReLU(bits=6, int_bits=3),
            QFixedLinear(64, 32, bits=6, int_bits=2),
            QFixedReLU(bits=6, int_bits=3),
            QFixedLinear(32, 32, bits=6, int_bits=2),
            QFixedReLU(bits=6, int_bits=3),
            QFixedLinear(32,  5, bits=6, int_bits=2),
        )

# Convert directly to Vivado HLS FPGA Firmware:
hls_cfg = hls4ml.utils.config_from_pytorch_model(
    seq_model, input_shape=(16,),
    granularity="name",
    default_precision="ap_fixed<16,6>",
    default_reuse_factor=1,
)
hls_cfg["Model"]["Strategy"] = "Latency"
hls_model = hls4ml.converters.convert_from_pytorch_model(
    seq_model, hls_config=hls_cfg, backend="Vivado"
)
hls_model.write()`;

export function FirmwareXRay({ data }: Props) {
  const [splitPct, setSplitPct] = useState(50);
  const [fwFile, setFwFile] = useState<'cpp' | 'h'>('cpp');

  const hlsSnippet =
    fwFile === 'cpp'
      ? data.firmware.project_cpp.split('\n').slice(0, 38).join('\n')
      : data.firmware.defines_h.split('\n').slice(0, 36).join('\n');

  return (
    <section id="firmware" className="relative py-24 sm:py-32 bg-[#04070d] border-t border-cyan-500/10">
      <div className="mx-auto max-w-7xl px-4 sm:px-6 lg:px-8">
        <div className="flex flex-col md:flex-row md:items-end justify-between gap-6 mb-10">
          <div className="max-w-2xl">
            <p className="font-mono-tech text-xs tracking-[0.22em] uppercase text-cyan-400">
              05 · PyTorch ↔ Silicon X-Ray (`hls4ml`)
            </p>
            <h2 className="mt-3 font-serif-display text-4xl sm:text-6xl text-white leading-[1.02]">
              From Python tensors to <span className="italic text-amber-300">C++ FPGA gates</span>.
            </h2>
            <p className="mt-3 text-slate-400 text-sm sm:text-base">
              Drag the X-Ray lens across the code to reveal the exact Vivado HLS C++ firmware
              generated by <code className="text-cyan-300">hls4ml v1.3.1</code> from our compressed
              PyTorch checkpoint—including <code className="text-amber-300">#pragma HLS PIPELINE</code>{' '}
              and <code className="text-amber-300">ap_fixed&lt;6,2&gt;</code> types.
            </p>
          </div>

          <div className="inline-flex rounded-xl bg-[#070b14] p-1 border border-slate-800 self-start">
            <button
              onClick={() => setFwFile('cpp')}
              className={`px-3 py-1.5 rounded-lg font-mono-tech text-xs transition cursor-pointer ${
                fwFile === 'cpp' ? 'bg-amber-500/20 text-amber-200 border border-amber-400/40' : 'text-slate-400'
              }`}
            >
              triggernet_6b_p75.cpp
            </button>
            <button
              onClick={() => setFwFile('h')}
              className={`px-3 py-1.5 rounded-lg font-mono-tech text-xs transition cursor-pointer ${
                fwFile === 'h' ? 'bg-amber-500/20 text-amber-200 border border-amber-400/40' : 'text-slate-400'
              }`}
            >
              defines.h
            </button>
          </div>
        </div>

        {/* Interactive X-Ray Code Morph Panel */}
        <div className="glass-panel rounded-2xl overflow-hidden mb-8">
          <div className="flex flex-wrap items-center justify-between gap-4 px-5 py-3 bg-[#070c16] border-b border-slate-800">
            <div className="flex items-center gap-4 font-mono-tech text-xs">
              <span className="text-cyan-300 font-semibold">LEFT: PyTorch Python</span>
              <span className="text-slate-600">|</span>
              <span className="text-amber-300 font-semibold">
                RIGHT: Generated Vivado HLS ({fwFile === 'cpp' ? 'triggernet_6b_p75.cpp' : 'defines.h'})
              </span>
            </div>
            <div className="flex items-center gap-3 font-mono-tech text-xs text-slate-400">
              <SlidersHorizontal className="h-3.5 w-3.5 text-cyan-400" />
              <span>X-Ray Split</span>
              <input
                type="range"
                min={8}
                max={92}
                value={splitPct}
                onChange={(e) => setSplitPct(Number(e.target.value))}
                className="w-32 sm:w-44 accent-cyan-400 cursor-pointer"
              />
            </div>
          </div>

          <div className="relative min-h-[380px] sm:min-h-[420px] font-mono-tech text-[11px] sm:text-xs leading-relaxed select-text">
            {/* Base Layer: Generated C++ HLS Firmware */}
            <pre className="p-5 sm:p-6 text-amber-200/95 bg-[#0a0905] overflow-x-auto min-h-[420px]">
              {hlsSnippet}
            </pre>

            {/* Clipped Top Layer: PyTorch Python Source */}
            <div
              className="absolute inset-0 overflow-hidden bg-[#050b14]"
              style={{ clipPath: `inset(0 ${100 - splitPct}% 0 0)` }}
            >
              <pre className="p-5 sm:p-6 text-cyan-200/95 overflow-x-auto min-h-[420px]">
                {PYTORCH_SNIPPET}
              </pre>
            </div>

            {/* Glowing Vertical X-Ray Beam Divider */}
            <div
              className="pointer-events-none absolute top-0 bottom-0 w-0.5 bg-gradient-to-b from-cyan-400 via-white to-amber-400 shadow-[0_0_18px_rgba(56,232,255,0.9)]"
              style={{ left: `${splitPct}%` }}
            />
          </div>
        </div>

        {/* Bottom Grid: 128-Weight Silicon ROM Matrix (w2.txt) + Bit-Accurate Parity Proof */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          {/* Real w2.txt Pruned Zero Silicon Grid */}
          <div className="lg:col-span-7 glass-panel rounded-2xl p-6">
            <div className="flex flex-wrap items-center justify-between gap-2 mb-3">
              <div>
                <span className="font-mono-tech text-[10px] uppercase tracking-widest text-slate-400">
                  Real Firmware ROM Slice · weights/w2.txt
                </span>
                <h3 className="text-lg font-semibold text-white">
                  {data.firmware.w2_zero_pct}% Exact Zeros Constant-Folded Out of Silicon
                </h3>
              </div>
              <div className="flex items-center gap-3 font-mono-tech text-[10px]">
                <span className="inline-flex items-center gap-1 text-cyan-300">
                  <span className="h-2.5 w-2.5 rounded-sm bg-cyan-400" /> +Weight
                </span>
                <span className="inline-flex items-center gap-1 text-rose-300">
                  <span className="h-2.5 w-2.5 rounded-sm bg-rose-400" /> −Weight
                </span>
                <span className="inline-flex items-center gap-1 text-slate-500">
                  <span className="h-2.5 w-2.5 rounded-sm bg-slate-900 border border-slate-700" /> 0.0 (No DSP)
                </span>
              </div>
            </div>

            <div className="grid grid-cols-16 gap-1 mt-4">
              {data.firmware.w2_sample.map((w, idx) => {
                const isZero = w === 0;
                const intensity = Math.min(1, Math.abs(w) * 1.35);
                const bg = isZero
                  ? 'rgba(15, 23, 42, 0.45)'
                  : w > 0
                    ? `rgba(56, 232, 255, ${0.28 + intensity * 0.72})`
                    : `rgba(242, 115, 91, ${0.28 + intensity * 0.72})`;
                return (
                  <div
                    key={idx}
                    title={`w2[${idx}] = ${w}`}
                    className="aspect-square rounded-[3px] border border-slate-800/70 transition hover:scale-125"
                    style={{ backgroundColor: bg }}
                  />
                );
              })}
            </div>
            <p className="mt-3 font-mono-tech text-[11px] text-slate-400">
              First 128 of {data.firmware.w2_total} Layer-1 weights. Every non-zero value is an exact
              multiple of <code className="text-amber-300">1/16 = 0.0625</code> (<code className="text-amber-300">ap_fixed&lt;6,2&gt;</code>).
            </p>
          </div>

          {/* Bit-Accurate Verification Parity Cards */}
          <div className="lg:col-span-5 glass-panel rounded-2xl p-6 flex flex-col justify-between">
            <div>
              <div className="flex items-center gap-2 font-mono-tech text-xs uppercase tracking-widest text-emerald-300 mb-3">
                <ShieldCheck className="h-4 w-4" />
                Bit-Accurate Verification (20,000 Test Jets)
              </div>
              <p className="text-xs text-slate-400 leading-relaxed mb-4">
                Comparing PyTorch QAT against exact <code className="text-cyan-300">ap_fixed</code>{' '}
                hardware emulation proves deployment preserves trigger physics down to 5 decimal places.
              </p>

              <div className="space-y-3">
                {data.hls_verification.map((row) => (
                  <div
                    key={row.Model}
                    className="rounded-xl bg-[#04070d] border border-slate-800/90 p-4 font-mono-tech"
                  >
                    <div className="flex items-center justify-between mb-2">
                      <span className="text-sm font-bold text-white">{row.Model}</span>
                      <span className="rounded bg-emerald-500/15 border border-emerald-400/30 px-2 py-0.5 text-[11px] text-emerald-300">
                        {row['Top-1 Agreement (%)'].toFixed(2)}% Match
                      </span>
                    </div>
                    <div className="grid grid-cols-3 gap-2 text-[11px]">
                      <div>
                        <span className="text-slate-500 block">PyTorch AUC</span>
                        <span className="text-cyan-300 font-semibold">{row['PyTorch AUC'].toFixed(5)}</span>
                      </div>
                      <div>
                        <span className="text-slate-500 block">ΔAUC</span>
                        <span className="text-amber-300 font-semibold">{row.ΔAUC.toFixed(5)}</span>
                      </div>
                      <div>
                        <span className="text-slate-500 block">Mean |Δlogit|</span>
                        <span className="text-slate-200 font-semibold">{row['Mean |Δlogit|'].toFixed(4)}</span>
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
